/**
 * 出闸前的最后一道：把「工具调用的文本协议」从回复里清掉。
 *
 * 起因（2026-10-28 15:08）：一个不是主人的人来问「今天你的说说是什么意思」，
 * 她（对外会话）想开 bash 去翻自己发过的说说——可对外会话是没有工具的
 * （见 `lib/session.js` 的 `lockdownTools`），于是同一句工具调用没有被当成调用，
 * 而是原样以 `<||DSML|| calls>…` 的形式漏进聊天，对方看到的是一堆乱码。
 *
 * 主人那边有真工具，这段会被解析掉，所以这个洞只出现在对外会话里——
 * 但正因为对外，漏出去的字（路径、服务器结构）是给陌生人看的，不能只当噪音。
 *
 * 规则很简单：整段标记连同里面的内容一起删掉；删完还剩话就照发，
 * 删空了就由调用方决定是沉默还是换一句兜底。
 */

/** 一段工具调用文本协议：从开标记一直吃到 `</…calls>`（有就吃到那里，没有就吃到结尾）。 */
const TOOL_BLOCK = /<[|｜]{2}\s*DSML[\s\S]*?(<\/[|｜]{2}\s*DSML\s*[|｜]{2}\s*calls\s*>|$)/gi

/** 删完整段之后可能剩下的零星标记（比如被截断、只有半个的）。 */
const TOOL_TAG = /\s*<\/?[|｜]{2}\s*DSML\s*[|｜]{2}[^>]*>/gi

/** 对外会话里，一轮话被清空之后该说的一句。不许沉默——对方是真在问事。 */
export const FALLBACK_REPLY = '刚才那下没接好，你再问一次呀～我听着呢'

/**
 * 把回复文本里的工具调用标记剥干净。
 *
 * @param input - 模型这一轮攒出来的文本。
 * @returns 清理后的文本；只剩标记时返回空串。
 */
export function stripToolMarkup(input) {
	if (typeof input !== 'string' || input === '') return ''
	const text = input
		.replace(TOOL_BLOCK, '')
		.replace(TOOL_TAG, '')
		.replace(/\n{3,}/g, '\n\n')
		.trim()
	return text
}
